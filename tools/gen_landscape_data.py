"""Regenerate compressed landscape blobs and low-memory thumbnails (requires Pillow)."""
from pathlib import Path
import json,hashlib
from PIL import Image,ImageOps
root=Path(__file__).resolve().parents[1]
assets=root/'assets/wallpapers/landscapes'
rows=json.loads((assets/'manifest.json').read_text())
c=['/* Generated by tools/gen_landscape_data.py; image license: CC0-1.0. */','#include "landscape_data.h"','']
assembly=['; Generated; photographic content CC0-1.0 (see asset manifest).','section .rodata progbits alloc noexec nowrite align=16']
h=['/* Generated; photograph sources and CC0 declarations: assets/wallpapers/landscapes. */','#ifndef LANDSCAPE_DATA_H','#define LANDSCAPE_DATA_H','#include "types.h"']
for row in rows:
    raw=(assets/row['file']).read_bytes()
    assert hashlib.sha256(raw).hexdigest()==row['sha256']
    im=Image.open(assets/row['file']).convert('RGB')
    assert list(im.size)==row['dimensions']
    ident='landscape_'+row['id'].replace('-','_')
    thumb=ImageOps.fit(im,(200,150),method=Image.Resampling.LANCZOS).tobytes()
    for suffix,data in [('thumb',thumb),('jpeg',raw)]:
        symbol=ident+'_'+suffix
        h.append(f'extern const uint8_t {symbol}[{len(data)}];')
        if suffix=='jpeg':
            assembly += ['align 16','global '+symbol,symbol+': incbin "assets/wallpapers/landscapes/'+row['file']+'"']
            continue
        c.append(f'const uint8_t {symbol}[{len(data)}] = {{')
        for n in range(0,len(data),32):c.append(','.join(f'0x{x:02x}' for x in data[n:n+32])+',')
        c.append('};')
h+=['#endif','']
(root/'kernel/landscape_data.c').write_text('\n'.join(c)+'\n')
(root/'kernel/landscape_data.h').write_text('\n'.join(h))
(root/'kernel/landscapebin.asm').write_text('\n'.join(assembly)+'\n')
print('Landscape bytes:',sum(x['bytes'] for x in rows))
